from __future__ import annotations

import logging
from typing import Any, Dict, List
from .state import AgentState
from llm import call_llm
from vault_logger import log, log_error

logger = logging.getLogger("mira.engine.chat.workflow.synthesis")


def synthesis_node(state: AgentState) -> Dict[str, Any]:
    """
    Step 5: Final Response Tool & Agent (Synthesis Node).
    The single final response tool in the chat workflow for all preceding tools.
    Takes the output from the preceding tool and the user's query, then returns the final response.
    MIRA's Final Response Agent requirements:
      1. Generate a short, friendly, funny roast based on the user's current message,
         current response, short-term memory, and relevant user information.
      2. Preserve all important context and factual information.
      3. Keep the response short, simple, natural, and relevant.
      4. Make the roast playful and personalized, never insulting or unrelated.
      5. Do not add extra information, explanations, or suggestions.
    """
    user_query = state.get("user_query", "").strip()
    node_outputs = state.get("node_outputs") or {}
    retrieved_ctx = state.get("retrieved_context") or {}
    chat_history = state.get("chat_history") or []
    user_profile = state.get("user_profile") or {}
    executed_node = node_outputs.get("executed_node") or state.get("next_node")

    log(f"[SynthesisNode] Executing final response agent for preceding node='{executed_node}'")

    # Extract previous agent's answer
    previous_answer = (
        state.get("final_response")
        or node_outputs.get("mira_assistant_response")
        or node_outputs.get("news_response")
        or node_outputs.get("weather_response")
        or node_outputs.get("activity_response")
        or node_outputs.get("history_response")
        or node_outputs.get("general_llm_response")
        or ""
    ).strip()

    # Verify that previous answer is not an unhandled third-party API error payload
    is_raw_error = any(
        err in previous_answer.lower()
        for err in (
            "gnews rejected",
            "syntax error (see https://docs.gnews.io",
            "{\"errors\":",
            "bad request (http 400)",
            "rate limit exceeded on all configured keys",
        )
    )

    # Fallback resolution if previous answer was not set or is a raw error
    if not previous_answer or is_raw_error:
        if retrieved_ctx:
            time_desc = retrieved_ctx.get("time_description", "the requested time")
            if not retrieved_ctx.get("found"):
                previous_answer = f"No activity records were found for {time_desc}."
            else:
                records = retrieved_ctx.get("records") or []
                lines = []
                for r in records[:30]:
                    ts = r.get("timestamp_formatted", "")
                    ts_end = r.get("timestamp_end_formatted")
                    time_display = f"{ts} - {ts_end}" if ts_end and ts_end != ts else ts
                    app = r.get("app_name", "Unknown App")
                    stext = str(r.get("summarized_text") or "").strip()
                    lines.append(f"- **{time_display}** — **{app}**: {stext}")
                previous_answer = "\n".join(lines)
        else:
            previous_answer = "No response was generated by the previous agent."

    # Format relevant user information
    user_name = user_profile.get("user_name", "User")
    info_items = [f"Name: {user_name}"]
    location_parts = [
        user_profile.get("city"),
        user_profile.get("state"),
        user_profile.get("country"),
    ]
    location_str = ", ".join([str(p).strip() for p in location_parts if p and str(p).strip()])
    if location_str:
        info_items.append(f"Location: {location_str}")
    if user_profile.get("role"):
        info_items.append(f"Role: {user_profile.get('role')}")
    if user_profile.get("notes"):
        info_items.append(f"Notes: {user_profile.get('notes')}")
    user_info_text = ", ".join(info_items)

    # Format short-term memory (recent conversation history)
    recent_turns: List[str] = []
    for item in chat_history[-6:]:
        role = item.get("role") or ("user" if "user" in item else "ai")
        content = str(item.get("content") or item.get("user") or item.get("ai") or "").strip()
        if content and content != user_query:
            speaker = user_name if role == "user" else "MIRA"
            recent_turns.append(f"{speaker}: {content}")
    history_text = "\n".join(recent_turns) if recent_turns else "None (first turn in conversation)"

    prompt = f"""You are MIRA, a helpful and witty personal AI companion.

Relevant User Information:
{user_info_text}

Short-Term Memory (Recent Conversation):
{history_text}

User's Current Message:
"{user_query}"

Current Response (Output from preceding tool):
{previous_answer}

Task:
Deliver the final response to the user by incorporating the factual information from the current response alongside a short, friendly, playful roast.

Strict Requirements:
1. Generate a short, friendly, funny roast based on the user's current message, current response, short-term memory, and relevant user information.
2. Preserve all important context and factual information.
3. Keep the response short, simple, natural, and relevant.
4. Make the roast playful and personalized, never insulting or unrelated.
5. Do not add extra information, explanations, or suggestions.
6. Respond strictly in English.

Final Response:"""

    try:
        final_answer = call_llm(prompt, work="synthesis").strip()
        if not final_answer or "The AI request could not be completed" in final_answer:
            final_answer = previous_answer
    except Exception as e:
        log_error(f"[SynthesisNode] Final response agent generation failed: {e}. Falling back to previous answer.")
        final_answer = previous_answer

    return {
        "final_response": final_answer,
    }
