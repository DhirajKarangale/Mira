from __future__ import annotations

import logging
from typing import Any, Dict, List
from .state import AgentState
from llm import call_llm
from vault_logger import log, log_error

logger = logging.getLogger("mira.engine.chat.workflow.synthesis")


def synthesis_node(state: AgentState) -> Dict[str, Any]:
    """
    Step 5: Final Response Agent (Synthesis Node).
    The last node in the chat workflow.
    Only rephrases the previous agent's answer into a friendly, natural response.
    Must not add, remove, modify, or assume any information.
    Preserves the original meaning and all factual details.
    Uses LLM work category 'synthesis' (higher temperature 0.7 from config.json).
    Answers strictly what the user asked with no unrelated explanations, suggestions, or filler.
    """
    user_query = state.get("user_query", "").strip()
    node_outputs = state.get("node_outputs") or {}
    retrieved_ctx = state.get("retrieved_context") or {}
    executed_node = node_outputs.get("executed_node") or state.get("next_node")

    log(f"[SynthesisNode] Rephrasing response for node='{executed_node}'")

    # Extract previous agent's answer
    previous_answer = (
        state.get("final_response")
        or node_outputs.get("weather_response")
        or node_outputs.get("activity_response")
        or node_outputs.get("history_response")
        or node_outputs.get("general_llm_response")
        or ""
    ).strip()

    # Fallback resolution if previous answer was not set
    if not previous_answer:
        if retrieved_ctx:
            time_desc = retrieved_ctx.get("time_description", "the requested time")
            if not retrieved_ctx.get("found"):
                previous_answer = f"No activity records were found for {time_desc}."
            else:
                records = retrieved_ctx.get("records") or []
                lines = []
                for r in records[:50]:
                    ts = r.get("timestamp_formatted", "")
                    ts_end = r.get("timestamp_end_formatted")
                    time_display = f"{ts} - {ts_end}" if ts_end and ts_end != ts else ts
                    app = r.get("app_name", "Unknown App")
                    stext = str(r.get("summarized_text") or "").strip()
                    lines.append(f"- **{time_display}** — **{app}**: {stext}")
                previous_answer = "\n".join(lines)
        else:
            previous_answer = "No response was generated by the previous agent."

    prompt = f"""You are the Final Response Agent of MIRA, a helpful and friendly desktop AI companion.

User Query: "{user_query}"

Previous Agent's Answer:
{previous_answer}

Task:
Rephrase the previous agent's answer into a friendly, natural response.

Strict Rules:
1. ONLY rephrase the previous agent's answer into a friendly, natural tone.
2. You MUST NOT add, remove, modify, or assume any information.
3. Preserve the original meaning and ALL factual details (such as names, timestamps, numbers, temperatures, weather conditions, applications, files, URLs, technical terms, and list items) exactly.
4. Concise response: Answer ONLY what the user asked.
5. Do NOT include unrelated information, additional explanations, suggestions, assumptions, or unnecessary introductions (such as "Certainly!", "Sure thing!", "Here is what you did:", or trailing questions like "Let me know if you need anything else!").
6. Do NOT include unsolicited greetings or conversational pleasantries.
7. CRITICAL INSTRUCTION FOR MISSING DATA: If the previous answer indicates that no records or data were found, Do NOT invent, assume, or hallucinate activities, applications, files, or tasks. State clearly that no records were found.
8. If the previous answer is a list or timeline of events, keep all items intact and accurate while making the phrasing natural and friendly.

Rephrased Response:"""

    try:
        final_answer = call_llm(prompt, work="synthesis").strip()
        if not final_answer or "The AI request could not be completed" in final_answer:
            final_answer = previous_answer
    except Exception as e:
        log_error(f"[SynthesisNode] Final response rephrasing failed: {e}. Falling back to original answer.")
        final_answer = previous_answer

    return {
        "final_response": final_answer,
    }
