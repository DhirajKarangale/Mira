from __future__ import annotations

import logging
from typing import Any, Dict, List
from .state import AgentState
from llm import call_llm
from vault_logger import log, log_error

logger = logging.getLogger("mira.engine.chat.workflow.synthesis")


def synthesis_node(state: AgentState) -> Dict[str, Any]:
    """
    Step 5: Final Response Agent (Synthesis Node).
    The last node in the chat workflow.
    - If previous agent already generated a direct, formatted answer (general_llm, history_answer,
      user_activity, weather, news, mira_assistant), returns it immediately (Fast Path), cutting latency in half.
    - If raw records need formatting, rephrases them cleanly into English.
    - Strict English only rule enforced.
    """
    user_query = state.get("user_query", "").strip()
    node_outputs = state.get("node_outputs") or {}
    retrieved_ctx = state.get("retrieved_context") or {}
    executed_node = node_outputs.get("executed_node") or state.get("next_node")

    log(f"[SynthesisNode] Evaluating response for node='{executed_node}'")

    # Extract previous agent's answer
    previous_answer = (
        state.get("final_response")
        or node_outputs.get("mira_assistant_response")
        or node_outputs.get("news_response")
        or node_outputs.get("weather_response")
        or node_outputs.get("activity_response")
        or node_outputs.get("history_response")
        or node_outputs.get("general_llm_response")
        or ""
    ).strip()

    # Verify that previous answer is not an unhandled third-party API error payload
    is_raw_error = any(
        err in previous_answer.lower()
        for err in (
            "gnews rejected",
            "syntax error (see https://docs.gnews.io",
            "{\"errors\":",
            "bad request (http 400)",
            "rate limit exceeded on all configured keys",
        )
    )

    # Fast Path: All nodes already generate high quality, structured, direct answers.
    # Bypassing redundant second/third LLM calls cuts chat response latency drastically!
    if executed_node in ("general_llm", "history_answer", "user_activity", "weather", "news", "mira_assistant") and previous_answer and not is_raw_error:
        log(f"[SynthesisNode] Fast path: node '{executed_node}' already generated complete answer. Bypassing extra synthesis LLM call.")
        return {
            "final_response": previous_answer,
        }
    elif is_raw_error:
        log_error(f"[SynthesisNode] Detected raw API error in answer from '{executed_node}'. Bypassing fast path to synthesize graceful AI response.")

    # Fallback resolution if previous answer was not set
    if not previous_answer:
        if retrieved_ctx:
            time_desc = retrieved_ctx.get("time_description", "the requested time")
            if not retrieved_ctx.get("found"):
                previous_answer = f"No activity records were found for {time_desc}."
            else:
                records = retrieved_ctx.get("records") or []
                lines = []
                for r in records[:30]:
                    ts = r.get("timestamp_formatted", "")
                    ts_end = r.get("timestamp_end_formatted")
                    time_display = f"{ts} - {ts_end}" if ts_end and ts_end != ts else ts
                    app = r.get("app_name", "Unknown App")
                    stext = str(r.get("summarized_text") or "").strip()
                    lines.append(f"- **{time_display}** — **{app}**: {stext}")
                previous_answer = "\n".join(lines)
        else:
            previous_answer = "No response was generated by the previous agent."

    prompt = f"""You are MIRA.

User Query: "{user_query}"

Source Information:
{previous_answer}

Task:
Provide a short, simple, and precise answer addressing strictly the user's query using the source information.

Strict Rules:
1. Respond strictly to the user's query with a short, simple, and precise answer.
2. Do not include extra information, unsolicited suggestions, or unrelated content.
3. Preserve factual details (names, timestamps, numbers, temperatures) accurately without modifying or assuming information.
4. If the source information indicates no records or data were found, state clearly that no records were found.
5. Respond strictly in English.

Answer:"""

    try:
        final_answer = call_llm(prompt, work="synthesis").strip()
        if not final_answer or "The AI request could not be completed" in final_answer:
            final_answer = previous_answer
    except Exception as e:
        log_error(f"[SynthesisNode] Final response rephrasing failed: {e}. Falling back to original answer.")
        final_answer = previous_answer

    return {
        "final_response": final_answer,
    }
